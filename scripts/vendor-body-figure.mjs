// Generates src/components/Anatomy/figure/paths.{male,female}.ts from the
// SVG path data in react-muscle-highlighter (MIT, dev dependency).
//
// Why vendor instead of using the package's component: it applies one colour
// per body part, so left and right cannot differ (the pain map needs that),
// and it renders at a fixed pixel size.
//
// What this does to the data:
//   - groups each part's sub-paths into one shape per (slug, side)
//   - renames sides to ANATOMICAL left/right. The package uses the viewer's
//     left/right, which is mirrored in the front view.
//   - records a bounding box per shape (used to place joint markers)
//
// Run: node scripts/vendor-body-figure.mjs

import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { svgPathBbox } = require("svg-path-bbox");

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkgDir = join(root, "node_modules/react-muscle-highlighter");
const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
const cjs = join(pkgDir, "dist/cjs");

const SOURCES = {
  male: {
    front: "assets/bodyFront.js",
    back: "assets/bodyBack.js",
    wrapper: "components/SvgMaleWrapper.js",
    viewBox: { front: [0, 0, 724, 1448], back: [724, 0, 724, 1448] },
  },
  female: {
    front: "assets/bodyFemaleFront.js",
    back: "assets/bodyFemaleBack.js",
    wrapper: "components/SvgFemaleWrapper.js",
    viewBox: { front: [-50, -40, 734, 1538], back: [756, 0, 774, 1448] },
  },
};

function outlines(wrapperFile) {
  const src = readFileSync(join(cjs, wrapperFile), "utf8");
  const found = [...src.matchAll(/d: "([^"]+)"/g)].map((m) => m[1]);
  if (found.length !== 2) {
    throw new Error(`${wrapperFile}: expected 2 outline paths, found ${found.length}`);
  }
  return { front: found[0], back: found[1] };
}

function round(n) {
  return Math.round(n * 10) / 10;
}

function buildView(assetFile, view, viewBox, outline) {
  const mod = require(join(cjs, assetFile));
  const parts = Object.values(mod).find(Array.isArray);
  const shapes = [];
  for (const part of parts) {
    for (const viewerSide of ["common", "left", "right"]) {
      const paths = part.path?.[viewerSide] ?? [];
      if (paths.length === 0) continue;
      // Sub-paths stay separate: some begin with a relative "m", which is
      // only treated as absolute at the very start of a path.
      let minX = Infinity;
      let minY = Infinity;
      let maxX = -Infinity;
      let maxY = -Infinity;
      for (const d of paths) {
        const [x0, y0, x1, y1] = svgPathBbox(d);
        minX = Math.min(minX, x0);
        minY = Math.min(minY, y0);
        maxX = Math.max(maxX, x1);
        maxY = Math.max(maxY, y1);
      }
      // Front view is mirrored: the viewer's left is the body's right.
      let side = "center";
      if (viewerSide !== "common") {
        side = view === "front" ? (viewerSide === "left" ? "right" : "left") : viewerSide;
      }
      shapes.push({
        slug: part.slug,
        side,
        paths,
        bbox: [round(minX), round(minY), round(maxX), round(maxY)],
      });
    }
  }
  return { viewBox, outline, shapes };
}

function emit(name, cfg) {
  const o = outlines(cfg.wrapper);
  const data = {
    front: buildView(cfg.front, "front", cfg.viewBox.front, o.front),
    back: buildView(cfg.back, "back", cfg.viewBox.back, o.back),
  };
  const out = join(root, "src/components/Anatomy/figure", `paths.${name}.ts`);
  mkdirSync(dirname(out), { recursive: true });
  const header = [
    "// GENERATED by scripts/vendor-body-figure.mjs. Do not edit by hand.",
    `// Source: ${pkg.name}@${pkg.version} (MIT). See ./LICENSE-react-muscle-highlighter.`,
    "// Sides are anatomical (the body's own left and right).",
    "",
    'import type { FigureData } from "@/lib/anatomy/figureTypes";',
    "",
    `export const ${name}Figure: FigureData = ${JSON.stringify(data, null, 1)};`,
    "",
  ].join("\n");
  writeFileSync(out, header);
  const count = data.front.shapes.length + data.back.shapes.length;
  console.log(`${name}: ${count} shapes -> ${out} (${Math.round(header.length / 1024)} KB)`);
}

for (const [name, cfg] of Object.entries(SOURCES)) emit(name, cfg);

writeFileSync(
  join(root, "src/components/Anatomy/figure/LICENSE-react-muscle-highlighter"),
  readFileSync(join(pkgDir, "LICENSE"), "utf8")
);
console.log("licence copied");
